#!/usr/bin/env python3
"""Сборка пакетов .apk (формат apk-tools v2) для OpenWrt 25.x из бинарников dist/.

Использование: scripts/mkapk.py [версия]
Результат:     dist/apk/corepanel_<версия>_<арх>_openwrt.apk

Пакет не подписан: ставится так — apk add --allow-untrusted ./corepanel_<версия>_<арх>_openwrt.apk
Формат (как у abuild): склеенные gzip-потоки «управляющий tar» + «tar с файлами» без маркера конца
у первого; в .PKGINFO записан sha256 сжатого потока с файлами (datahash). apk-tools 3 читает такой формат.
Внутри архитектура noarch: нужный бинарник выбираете вы (arm64, armv7, mipsle...), как и с .ipk.
"""
import gzip, hashlib, io, os, re, sys, tarfile, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCHS = ["mipsle", "mips", "mips64", "armv7", "armv5", "arm64", "amd64", "riscv64"]
URL = "https://github.com/phenomenonRT/panel_awg-box_sing-box"
INIT = os.path.join(ROOT, "scripts", "ipk", "openwrt.init")

POST_INSTALL = """#!/bin/sh
[ -n "${IPKG_INSTROOT:-}" ] && exit 0
/etc/init.d/corepanel enable
/etc/init.d/corepanel start 2>/dev/null
echo "corepanel запущен: http://<адрес-роутера>:8088 (вход без пароля из локальной сети; включить пароль root — раздел «Система»)"
exit 0
"""
POST_UPGRADE = """#!/bin/sh
[ -n "${IPKG_INSTROOT:-}" ] && exit 0
/etc/init.d/corepanel enable
/etc/init.d/corepanel restart 2>/dev/null
exit 0
"""
PRE_DEINSTALL = """#!/bin/sh
[ -n "${IPKG_INSTROOT:-}" ] && exit 0
/etc/init.d/corepanel stop 2>/dev/null
/etc/init.d/corepanel disable 2>/dev/null
exit 0
"""


def apk_version(ver):
    """0.1.82 → 0.1.82-r0; 0.1.82-dev.3 → 0.1.82_pre3-r0 (pre сортируется раньше релиза)."""
    m = re.fullmatch(r"(\d+(?:\.\d+)*)(?:-dev(?:\.(\d+))?)?", ver)
    if not m:
        raise SystemExit("неверная версия: " + ver)
    base, dev = m.group(1), m.group(2)
    if "-dev" in ver:
        base += "_pre" + (dev or "0")
    return base + "-r0"


def entry(name, data=b"", mode=0o644, typ=tarfile.REGTYPE, mtime=0):
    ti = tarfile.TarInfo(name)
    ti.type, ti.mode, ti.mtime = typ, mode, mtime
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = "root"
    ti.size = len(data) if typ == tarfile.REGTYPE else 0
    buf = ti.tobuf(tarfile.USTAR_FORMAT)
    if typ == tarfile.REGTYPE:
        buf += data + b"\0" * (-len(data) % 512)
    return buf


def gz(b):
    return gzip.compress(b, 9, mtime=0)


def build(binary, ver, now):
    data_files = open(binary, "rb").read()
    init = open(INIT, "rb").read()
    d = b"".join([
        entry("etc/", mode=0o755, typ=tarfile.DIRTYPE, mtime=now),
        entry("etc/init.d/", mode=0o755, typ=tarfile.DIRTYPE, mtime=now),
        entry("etc/init.d/corepanel", init, 0o755, mtime=now),
        entry("usr/", mode=0o755, typ=tarfile.DIRTYPE, mtime=now),
        entry("usr/bin/", mode=0o755, typ=tarfile.DIRTYPE, mtime=now),
        entry("usr/bin/corepanel", data_files, 0o755, mtime=now),
    ]) + b"\0" * 1024  # конец архива — только у последнего потока
    data_gz = gz(d)
    info = "\n".join([
        "# Generated by corepanel scripts/mkapk.py",
        "pkgname = corepanel",
        "pkgver = " + apk_version(ver),
        "pkgdesc = Web panel for amnezia-box (OpenWrt)",
        "url = " + URL,
        "builddate = %d" % now,
        "packager = corepanel",
        "size = %d" % (len(data_files) + len(init)),
        "arch = noarch",
        "origin = corepanel",
        "license = MIT",
        "datahash = " + hashlib.sha256(data_gz).hexdigest(),
        "",
    ]).encode()
    c = b"".join([
        entry(".PKGINFO", info, 0o644, mtime=now),
        entry(".post-install", POST_INSTALL.encode(), 0o755, mtime=now),
        entry(".post-upgrade", POST_UPGRADE.encode(), 0o755, mtime=now),
        entry(".pre-deinstall", PRE_DEINSTALL.encode(), 0o755, mtime=now),
    ])  # без маркера конца: tar продолжается следующим gzip-потоком
    return gz(c) + data_gz


def verify(path, ver):
    """Разбирает собранный файл так, как это делает apk: два gzip-потока подряд — один tar."""
    raw = open(path, "rb").read()
    mem, off = [], 0
    while off < len(raw):
        d = __import__("zlib").decompressobj(31)
        out = d.decompress(raw[off:])
        used = len(raw) - off - len(d.unused_data)
        mem.append((raw[off:off + used], out))
        off += used
    assert len(mem) == 2, "ожидалось 2 gzip-потока, найдено %d" % len(mem)
    tar = tarfile.open(fileobj=io.BytesIO(mem[0][1] + mem[1][1]), mode="r:")
    names = tar.getnames()
    assert names[:4] == [".PKGINFO", ".post-install", ".post-upgrade", ".pre-deinstall"], names
    assert "usr/bin/corepanel" in names and "etc/init.d/corepanel" in names, names
    pkginfo = tar.extractfile(".PKGINFO").read().decode()
    want = hashlib.sha256(mem[1][0]).hexdigest()
    assert "datahash = " + want in pkginfo, "datahash не совпал"
    assert "pkgver = " + apk_version(ver) in pkginfo
    # файл с содержимым не пустой, права исполняемые
    assert tar.getmember("usr/bin/corepanel").mode == 0o755 and tar.getmember("usr/bin/corepanel").size > 1000


def main():
    ver = sys.argv[1] if len(sys.argv) > 1 else "0.1.0"
    now = int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))
    out = os.path.join(ROOT, "dist", "apk")
    os.makedirs(out, exist_ok=True)
    for a in ARCHS:
        b = os.path.join(ROOT, "dist", "corepanel-linux-" + a)
        if not os.path.exists(b):
            print("нет " + b, file=sys.stderr)
            continue
        f = os.path.join(out, "corepanel_%s_%s_openwrt.apk" % (ver, a))
        with open(f, "wb") as fh:
            fh.write(build(b, ver, now))
        verify(f, ver)
        print("==> " + f)


if __name__ == "__main__":
    main()
